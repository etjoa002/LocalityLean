"""Figure and numbers for the harmonic-chain example of chapter 7 of the lecture notes.

Computes, for the chain H = ½ Σ (p² + ω² q²) + ½ λ Σ (q_x − q_{x+1})² on n sites with the label
generator K = (J M)^T (the flow of the Weyl labels, checks/m5_check.py), at times t:
  exact(y)  = max of |σ(T_t f, g)| over f at site 0 and g at site y with all coordinates of modulus
              at most 1 (attained at sign vectors, since the form is bilinear),
  bound(y)  = Σ_{i,j} (e^{t|K|})_{(y,i),(0,j)}, the doubled-index bound of Theorem 7.x for
              |f_a| ≤ 1, |g_b| ≤ 1 at the two sites,
  range(y)  = 4 (v t)^y / y! e^{v t} with v the largest row sum of |K| (four coordinate pairs),
and writes checks/out/harmonic.tex, a TikZ semi-logarithmic plot. It prints the
numbers quoted in the chapter.

    python checks/m5_figure.py [--n 12] [--omega 1] [--lam 1] [--times 0.5 1 2]
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
from scipy.linalg import expm

STYLES = ["Blue", "black", "Blue!60!black"]
YMIN, YMAX = -13, 1
XS, YS = 0.5, 0.42


def chain_matrices(n: int, omega: float, lam: float):
    A = np.zeros((n, n))
    for x in range(n):
        deg = (1 if x + 1 < n else 0) + (1 if x - 1 >= 0 else 0)
        A[x, x] = omega ** 2 + lam * deg
        if x + 1 < n:
            A[x, x + 1] = A[x + 1, x] = -lam
    # coordinates ordered (x, i) with i = 0 (q), 1 (p): index 2x + i
    K = np.zeros((2 * n, 2 * n))
    for x in range(n):
        for y in range(n):
            K[2 * x + 0, 2 * y + 1] = -A[x, y]      # (Kf)^q_x = -Σ_y A_xy f^p_y
        K[2 * x + 1, 2 * x + 0] = 1.0                # (Kf)^p_x = f^q_x
    Om = np.zeros((2 * n, 2 * n))
    for x in range(n):
        Om[2 * x, 2 * x + 1] = 1.0
        Om[2 * x + 1, 2 * x] = -1.0
    return A, K, Om


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=12)
    ap.add_argument("--omega", type=float, default=1.0)
    ap.add_argument("--lam", type=float, default=1.0)
    ap.add_argument("--times", type=float, nargs="+", default=[0.5, 1.0, 2.0])
    ap.add_argument("--out", default="checks/out/harmonic.tex")
    args = ap.parse_args()
    n, omega, lam = args.n, args.omega, args.lam
    A, K, Om = chain_matrices(n, omega, lam)
    assert np.allclose(K.T @ Om + Om @ K, 0)
    absK = np.abs(K)
    v = absK.sum(axis=1).max()
    ys = list(range(1, n))

    def y(val: float) -> float:
        return (math.log10(max(val, 10.0 ** (YMIN - 1))) - YMIN) * YS

    L = []
    L.append("% Figure: the harmonic bound on the chain of chapter 7, generated by checks/m5_figure.py.")
    L.append("% Transcription (for cheap agents): axes, the site y of the second observable to the right")
    L.append("% (the first sits at site 0) and the commutator quantity upward on a logarithmic scale; per")
    L.append("% time t a solid curve with dots (the exact |sigma(T_t f, g)|, maximized over unit f, g) and")
    L.append("% a dashed curve (the entrywise bound), both falling exponentially in y beyond a front that")
    L.append("% moves with t; the bound lies above the exact curve with the same kind of decay. Curves stop")
    L.append("% where they fall below the bottom of the scale; a legend at the top right names the times")
    L.append("% (solid = exact, dashed = bound).")
    L.append(f"\\begin{{tikzpicture}}[x={XS}cm,y=1cm,>={{Stealth[length=5pt]}}]")
    L.append(f"  \\draw[->] (0,0) -- ({n + 0.6},0) node[right,font=\\small] {{$y$}};")
    L.append(f"  \\draw[->] (0,0) -- (0,{y(10 ** YMAX) + 0.3:.2f}) node[above,font=\\small] {{$|\\sigma(T_tf,g)|$}};")
    for e in range(-12, YMAX + 1, 3):
        L.append(f"  \\draw (0.15,{y(10 ** e):.2f}) -- (-0.15,{y(10 ** e):.2f}) node[left,font=\\scriptsize] {{$10^{{{e}}}$}};")
    for yy in ys:
        L.append(f"  \\draw ({yy},0.06) -- ({yy},-0.06) node[below,font=\\scriptsize] {{{yy}}};")
    report = []
    for t, st in zip(args.times, STYLES):
        T = expm(t * K)
        E = expm(t * absK)
        exact, bound, rng = [], [], []
        for yy in ys:
            # sigma(T f, g) = (T f) . (Om g); f at site 0, g at site yy: the 2x2 block of Om^T T? use the
            # bilinear form restricted: B_{ij} = sigma(T e_{(0,j)}, e_{(yy,i)})
            B = np.zeros((2, 2))
            for i in range(2):
                for j in range(2):
                    f = np.zeros(2 * n); f[2 * 0 + j] = 1.0
                    g = np.zeros(2 * n); g[2 * yy + i] = 1.0
                    B[i, j] = (T @ f) @ (Om @ g)
            # the maximum of the bilinear form over |f_a| ≤ 1, |g_b| ≤ 1 at the two sites is attained
            # at sign vectors (a bilinear form on a box): enumerate the sixteen choices
            signs = [np.array(s) for s in ((1, 1), (1, -1), (-1, 1), (-1, -1))]
            exact.append(max(abs(sg @ B @ sf) for sf in signs for sg in signs))
            bound.append(sum(E[2 * yy + i, 2 * 0 + j] for i in range(2) for j in range(2)))
            rng.append(4 * (v * t) ** yy / math.factorial(yy) * math.exp(v * t))
        floor = 10.0 ** YMIN
        pe = [(yy, val) for yy, val in zip(ys, exact) if val >= floor]
        pb = [(yy, val) for yy, val in zip(ys, bound) if val >= floor]
        pth = " -- ".join(f"({yy},{y(val):.3f})" for yy, val in pe)
        L.append(f"  \\draw[{st},thick] {pth};")
        for yy, val in pe:
            L.append(f"  \\fill[{st}] ({yy},{y(val):.3f}) circle (1.2pt);")
        pth = " -- ".join(f"({yy},{y(val):.3f})" for yy, val in pb)
        L.append(f"  \\draw[{st},dashed] {pth};")
        k = args.times.index(t)
        ly = y(10 ** YMAX) - 0.1 - 0.42 * k
        L.append(f"  \\draw[{st},thick] ({n - 4.2},{ly:.2f}) -- ({n - 3.2},{ly:.2f});")
        L.append(f"  \\draw[{st},dashed] ({n - 2.9},{ly:.2f}) -- ({n - 1.9},{ly:.2f});")
        L.append(f"  \\node[{st},anchor=west,font=\\scriptsize] at ({n - 1.7},{ly:.2f}) {{$t={t:g}$}};")
        fit = [yy for yy in ys if 3 <= yy <= n - 2]
        se = -np.polyfit(fit, np.log([exact[yy - 1] for yy in fit]), 1)[0]
        sb = -np.polyfit(fit, np.log([bound[yy - 1] for yy in fit]), 1)[0]
        front = min(yy for yy, val in zip(ys, exact) if val < 0.1)
        ratio = [b / e for b, e in zip(bound, exact)]
        report.append((t, front, se, sb, min(ratio), max(ratio), exact, bound, rng))
    L.append("\\end{tikzpicture}")
    Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}; n = {n}, omega = {omega}, lambda = {lam}, v = {v:g}")
    for t, front, se, sb, lo, hi, exact, bound, rng in report:
        print(f"t = {t:g}: exact < 0.1 from y = {front}; decay per site: exact exp(-{se:.2f} y), "
              f"bound exp(-{sb:.2f} y); bound/exact from {lo:.3g} to {hi:.3g}")
        for yy in (1, 2, 3, 4, 5):
            print(f"   y = {yy}: exact {exact[yy-1]:.2e}  bound {bound[yy-1]:.2e}  range form {rng[yy-1]:.2e}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
