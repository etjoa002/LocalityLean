"""Figure and numbers for the twelve-qubit truncation example (chapter 5 of the lecture notes).

Reads the checkpoint written by checks/long_chain.py (default checks/data/long-chain-n12.json)
and writes checks/out/longchain.tex, a TikZ semi-logarithmic plot of the error
eps_r(t) = ||A(t) - P_{X_r} A(t)|| against r for each time, with the walk bound dashed where it is
below the trivial bound 2||a|| = 2. It also prints the numbers quoted in the example: the first r
with eps < 0.1 at each time (the front), the least-squares decay rate per site of the error and of
the walk bound over r = 3..10, and the range of the ratio walk bound / error.

    python checks/long_chain_figure.py [--data checks/data/long-chain-n12.json]
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

TIMES = [0.25, 0.5, 1.0, 2.0]
STYLES = ["Blue", "black", "Blue!60!black", "black!60"]
YMIN, YMAX = -13, 1  # decades
XS, YS = 0.65, 0.42  # cm per site, cm per decade


def key(points: dict, t: float, r: int) -> dict:
    for k in (f"{t:g}:{r}", f"{t}:{r}"):
        if k in points:
            return points[k]
    raise KeyError((t, r))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="checks/data/long-chain-n12.json")
    ap.add_argument("--out", default="checks/out/longchain.tex")
    args = ap.parse_args()
    d = json.loads(Path(args.data).read_text(encoding="utf-8"))
    n, pts = d["n"], d["points"]
    rs = list(range(n - 1))  # r = n-1 gives X_r = Lambda, error zero, not plotted

    def y(v: float) -> float:
        return (math.log10(v) - YMIN) * YS

    L = []
    L.append("% Figure: the twelve-qubit truncation errors of Example ex:truncation, generated by")
    L.append("% checks/long_chain_figure.py from the data of checks/long_chain.py. Transcription (for")
    L.append("% cheap agents): axes, the radius r = 0..10 of the region X_r to the right and the error")
    L.append("% eps_r(t) upward on a logarithmic scale from 1e-12 to 10; one solid curve with dots per")
    L.append("% time t = 0.25, 0.5, 1, 2 (labelled at its right end), each falling exponentially in r")
    L.append("% beyond a front that moves to the right with t; the walk bound dashed, for t = 0.25 and")
    L.append("% 0.5 only, where it is below the trivial bound 2 (a thin horizontal line at 2).")
    L.append(f"\\begin{{tikzpicture}}[x={XS}cm,y=1cm,>={{Stealth[length=5pt]}}]")
    L.append(f"  \\draw[->] (0,0) -- ({n - 1 + 0.6},0) node[right,font=\\small] {{$r$}};")
    L.append(f"  \\draw[->] (0,0) -- (0,{y(10 ** YMAX) + 0.3:.2f}) node[above,font=\\small] {{$\\delta_r(t)$}};")
    for e in range(-12, YMAX + 1, 3):
        L.append(f"  \\draw (0.15,{y(10 ** e):.2f}) -- (-0.15,{y(10 ** e):.2f}) node[left,font=\\scriptsize] {{$10^{{{e}}}$}};")
    for r in rs:
        L.append(f"  \\draw ({r},0.06) -- ({r},-0.06) node[below,font=\\scriptsize] {{{r}}};")
    L.append(f"  \\draw[thin,black!50] (0,{y(2):.2f}) -- ({n - 1 + 0.3},{y(2):.2f}) node[right,font=\\scriptsize,black] {{$2\\norm a$}};")
    report = []
    for t, st in zip(TIMES, STYLES):
        eps = [key(pts, t, r)["eps"] for r in rs]
        wb = [key(pts, t, r)["walk_bound"] for r in rs]
        pth = " -- ".join(f"({r},{y(v):.3f})" for r, v in zip(rs, eps))
        L.append(f"  \\draw[{st},thick] {pth};")
        for r, v in zip(rs, eps):
            L.append(f"  \\fill[{st}] ({r},{y(v):.3f}) circle (1.2pt);")
        L.append(f"  \\node[{st},anchor=west,font=\\scriptsize] at ({rs[-1] + 0.15},{y(eps[-1]):.3f}) {{$t={t:g}$}};")
        nz = [(r, v) for r, v in zip(rs, wb) if v < 2]
        if len(nz) >= 2:
            pth = " -- ".join(f"({r},{y(v):.3f})" for r, v in nz)
            L.append(f"  \\draw[{st},dashed] {pth};")
            L.append(f"  \\node[{st},anchor=west,font=\\scriptsize] at ({rs[-1] + 0.15},{y(nz[-1][1]):.3f}) {{bound, $t={t:g}$}};")
        fit = list(range(3, n - 1))
        se = -np.polyfit(fit, np.log([key(pts, t, r)["eps"] for r in fit]), 1)[0]
        sw = -np.polyfit(fit, np.log([key(pts, t, r)["walk_bound"] for r in fit]), 1)[0]
        front = min(r for r in rs if key(pts, t, r)["eps"] < 0.1)
        ratio = [key(pts, t, r)["walk_bound"] / key(pts, t, r)["eps"] for r in rs]
        first_nontrivial = next((r for r in rs if key(pts, t, r)["walk_bound"] < 2), None)
        report.append((t, front, se, sw, min(ratio), max(ratio), first_nontrivial))
    L.append("\\end{tikzpicture}")
    Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    for t, front, se, sw, lo, hi, fnt in report:
        print(f"t = {t:g}: eps < 0.1 from r = {front}; decay per site: error exp(-{se:.2f} r), "
              f"walk bound exp(-{sw:.2f} r); walk/error from {lo:.3g} to {hi:.3g}; "
              f"walk bound below 2 from r = {fnt}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
